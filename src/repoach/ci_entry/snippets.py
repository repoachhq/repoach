"""The CI jobs ``repoach init --ci gitlab|github`` writes.

Each job installs a pinned repoach with every secret removed from the
install step's environment (the one step that runs code fetched at job
time), then runs ``repoach ci review``, which receives the secrets. On
GitLab the job lives in its own file, ``.repoach/ci/gitlab-review.yml``,
pulled in with ``include:``; ``.gitlab-ci.yml`` is never edited, only the
two-line ``include`` is printed. On GitHub the workflow is its own file,
``.github/workflows/repoach-review.yml``; no existing workflow is edited.

A file already holding the rendered content is ``unchanged``; one
holding something else is left alone unless ``--force`` (``differs``).
"""

from __future__ import annotations

from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict

from .variables import (
    DIRECT_KEY_VARS,
    GATEWAY_TOKEN_VAR,
    GATEWAY_URL_VAR,
    PASSTHROUGH_VARS,
    POST_VAR,
)

CiKind = Literal["gitlab", "github"]

REPOACH_GIT_URL = "https://github.com/repoachhq/repoach"
DEFAULT_REF = "develop"
"""Git ref installed when neither ``--ref`` nor ``--pypi-version`` is given."""

GITLAB_JOB_PATH = Path(".repoach") / "ci" / "gitlab-review.yml"
GITHUB_WORKFLOW_PATH = Path(".github") / "workflows" / "repoach-review.yml"

GITLAB_JOB_NAME = "review:advisory"

PYTHON_IMAGE = (
    "python:3.12-slim@sha256:a6e34c598f2467ed0e9a8d349809fcd8b5c603269512df273a0bb1784edc11b1"
)
CHECKOUT_ACTION = "actions/checkout@34e114876b0b11c390a56381ad16ebd13914f8d5"
SETUP_PYTHON_ACTION = "actions/setup-python@a26af69be951a213d495a4c3e4e4022e16d87065"


class InstallTarget(BaseModel):
    """What the job installs: a git ref of repoach or a PyPI version.

    Attributes:
        ref: Git ref (tag, SHA or branch) of the repoach repository.
        pypi_version: Exact PyPI version; wins over ``ref``.
    """

    model_config = ConfigDict(frozen=True)

    ref: str = DEFAULT_REF
    pypi_version: str | None = None

    def requirement(self) -> str:
        """Return the pip requirement string."""
        if self.pypi_version:
            return f"repoach=={self.pypi_version}"
        return f"repoach @ git+{REPOACH_GIT_URL}@{self.ref}"


def scrubbed(command: str, *extra: str) -> str:
    """Run ``command`` with only the allow-listed variables that are set.

    A one-line Python ``execvpe`` (Python is in both job images before
    repoach is) rebuilds the environment from
    :data:`~repoach.ci_entry.variables.PASSTHROUGH_VARS` alone, so no
    credential the job holds reaches the step, under any name; an unset
    name stays unset rather than becoming empty. ``extra`` adds
    ``NAME=value`` assignments through ``env``. Expansions in
    ``command`` (``$REPOACH_INSTALL``) are done by the job's own shell.

    Args:
        command: The command to run.
        *extra: ``NAME=value`` assignments the step needs.
    """
    keep = ",".join(f'"{name}"' for name in PASSTHROUGH_VARS)
    scrub = (
        f"import os,sys;keep={{{keep}}};"
        "os.execvpe(sys.argv[1],sys.argv[1:],"
        "{n:v for n,v in os.environ.items() if n in keep})"
    )
    added = f"env {' '.join(extra)} " if extra else ""
    return f"python3 -c '{scrub}' {added}{command}"


def _apt_command() -> str:
    """Return the scrubbed ``apt-get`` step installing git and glab."""
    return scrubbed(
        "sh -c 'apt-get update -qq && apt-get install -y -qq --no-install-recommends "
        "git glab ca-certificates >/dev/null'",
        "DEBIAN_FRONTEND=noninteractive",
    )


def _install_command() -> str:
    """Return the scrubbed install step for ``$REPOACH_INSTALL``."""
    return scrubbed('python -m pip install --quiet --disable-pip-version-check "$REPOACH_INSTALL"')


def render_gitlab_job(target: InstallTarget) -> str:
    """Render the ``review:advisory`` GitLab job (an ``include:`` target)."""
    return (
        "# Generated by repoach init --ci gitlab. Pulled in by .gitlab-ci.yml with:\n"
        "#   include:\n"
        f"#     - local: {GITLAB_JOB_PATH.as_posix()}\n"
        "# Set REPOACH_GITLAB_TOKEN (masked) and either REPOACH_ANTHROPIC_API_KEY\n"
        f"# (direct) or {GATEWAY_URL_VAR} + {GATEWAY_TOKEN_VAR} (gateway) as CI/CD variables.\n"
        f"{GITLAB_JOB_NAME}:\n"
        "  needs: []\n"
        "  rules:\n"
        '    - if: $CI_PIPELINE_SOURCE == "merge_request_event"\n'
        "  allow_failure: true\n"
        "  interruptible: true\n"
        "  timeout: 30 minutes\n"
        f"  image: {PYTHON_IMAGE}\n"
        "  variables:\n"
        f'    REPOACH_INSTALL: "{target.requirement()}"\n'
        f'    {POST_VAR}: "0"\n'
        "  script:\n"
        f"    - {_apt_command()}\n"
        f"    - {_install_command()}\n"
        "    - repoach ci review\n"
    )


def render_github_workflow(target: InstallTarget) -> str:
    """Render the ``repoach review`` GitHub Actions workflow."""
    return (
        "# Generated by repoach init --ci github.\n"
        "# Secrets: REPOACH_ANTHROPIC_API_KEY (direct mode) or REPOACH_ANTHROPIC_AUTH_TOKEN\n"
        "# with the variable REPOACH_LLM_PROXY_BASE_URL (gateway mode).\n"
        "# Variable REPOACH_ADVISORY_POST=1 turns posting on; anything else is a dry run.\n"
        "name: repoach review\n"
        "on:\n"
        "  pull_request:\n"
        "    types: [opened, synchronize, reopened, ready_for_review]\n"
        "permissions:\n"
        "  contents: read\n"
        "  pull-requests: write\n"
        "concurrency:\n"
        "  group: repoach-review-${{ github.event.pull_request.number }}\n"
        "  cancel-in-progress: true\n"
        "jobs:\n"
        "  review:\n"
        "    runs-on: ubuntu-latest\n"
        "    continue-on-error: true\n"
        "    timeout-minutes: 30\n"
        "    steps:\n"
        f"      - uses: {CHECKOUT_ACTION}\n"
        f"      - uses: {SETUP_PYTHON_ACTION}\n"
        "        with:\n"
        '          python-version: "3.12"\n'
        "      - name: Install repoach (no secret in this step)\n"
        "        env:\n"
        f'          REPOACH_INSTALL: "{target.requirement()}"\n'
        f"        run: {_install_command()}\n"
        "      - name: Review\n"
        "        env:\n"
        "          GH_TOKEN: ${{ secrets.GITHUB_TOKEN }}\n"
        f"          {POST_VAR}: ${{{{ vars.{POST_VAR} }}}}\n"
        f"          {DIRECT_KEY_VARS[0]}: ${{{{ secrets.{DIRECT_KEY_VARS[0]} }}}}\n"
        f"          {GATEWAY_URL_VAR}: ${{{{ vars.{GATEWAY_URL_VAR} }}}}\n"
        f"          {GATEWAY_TOKEN_VAR}: ${{{{ secrets.{GATEWAY_TOKEN_VAR} }}}}\n"
        "        run: repoach ci review\n"
    )


def gitlab_include_snippet() -> str:
    """Return the lines to add to ``.gitlab-ci.yml`` (never written by repoach)."""
    return f"include:\n  - local: {GITLAB_JOB_PATH.as_posix()}\n"


CiAction = Literal["create", "unchanged", "differs", "overwrite"]


class CiInitPlan(BaseModel):
    """What ``init --ci`` would do to one file.

    Attributes:
        path: The file, relative to the project root.
        action: ``create``, ``unchanged``, ``differs`` (left alone) or
            ``overwrite`` (``--force``).
        content: The rendered content.
    """

    model_config = ConfigDict(frozen=True)

    path: Path
    action: CiAction
    content: str

    def describe(self, *, dry_run: bool) -> str:
        """Return the one line ``init`` prints for this file."""
        where = self.path.as_posix()
        if self.action == "unchanged":
            return f"unchanged {where}"
        if self.action == "differs":
            return f"differs {where} (left untouched; --force rewrites it)"
        if dry_run:
            return f"would {self.action} {where}"
        return f"{'created' if self.action == 'create' else 'overwritten'} {where}"


def render(kind: CiKind, target: InstallTarget) -> tuple[Path, str]:
    """Return the file path and content for ``kind``."""
    if kind == "gitlab":
        return GITLAB_JOB_PATH, render_gitlab_job(target)
    return GITHUB_WORKFLOW_PATH, render_github_workflow(target)


def plan_ci_init(root: Path, kind: CiKind, target: InstallTarget, *, force: bool) -> CiInitPlan:
    """Decide what ``init --ci`` does to the job file under ``root``."""
    path, content = render(kind, target)
    existing = root / path
    if not existing.exists():
        return CiInitPlan(path=path, action="create", content=content)
    if existing.read_text(encoding="utf-8") == content:
        return CiInitPlan(path=path, action="unchanged", content=content)
    return CiInitPlan(path=path, action="overwrite" if force else "differs", content=content)


def apply_ci_init(root: Path, plan: CiInitPlan) -> None:
    """Write the file when the plan says ``create`` or ``overwrite``."""
    if plan.action not in ("create", "overwrite"):
        return
    target = root / plan.path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(plan.content, encoding="utf-8")
